def get_product_embedding_seeders(products: list[dict], chaos_rate: float = 0.05, apply_chaos: bool = True) -> list[dict]:
    """
    Generates a batch of embeddings based on the list of products generated by the product seeder.
    Since this is an initial mock for future PGVector tests, the vectors will be arrays
    with random values between -1.0 and 1.0, simulating the output of real models.
    """
    batch = []

    for product in products:

        product_id = product["product_id"]
        product_name = product["product_name"]

        # 1. Simulate the source_data_hash (Cache/ETL control)
        # In real life, this would be the hash of the text + metadata concatenated for embedding
        text_to_embed = f"{product_name} {product['productdetails'].get('brand', '')} {product['productdetails'].get('material', '')}"
        source_hash = hashlib.sha256(text_to_embed.encode('utf-8')).hexdigest()

        # 2. Random vector generation (PGVector)
        # OpenAI text-embedding-3-small has 1536 dimensions
        desc_vector = [round(random.uniform(-1.0, 1.0), 6) for _ in range(1536)]

        # Clip ViT-Base-Patch32 has 512 dimensions
        img_vector = [round(random.uniform(-1.0, 1.0), 6) for _ in range(512)]

        # 3. Traceability metadata (per AIModelMetadata)
        ai_metadata = {
            "text_model": "openai-text-embedding-3-small",
            "image_model": "openai-clip-vit-base-patch32",
            "generation_method": "mock_seeder_batch"
        }

        # 4. Assemble the payload
        # SQLAlchemy's pgvector and jsonb handle the conversions internally at the service layer
        batch.append({
            "product_id": product_id,
            "description_vector": desc_vector,
            "image_vector": img_vector,
            "source_data_hash": source_hash,
            "ai_metadata": ai_metadata,
            "created_at": datetime.now(),
            "updated_at": datetime.now(),
            "is_active": True,
            "row_guid": str(uuid.uuid4())
        })

    if apply_chaos:
        batch = apply_embedding_chaos(batch, chaos_rate=chaos_rate)

    return batch


async def seed_product_embeddings(chaos_rate: float = 0.05, apply_chaos: bool = True):
    """Generates embeddings for REAL products in the database that don't have an embedding yet (product_id is unique)."""
    async with AsyncSessionLocal() as session:
        already_embedded = set((await session.execute(select(ProductEmbeddingModel.product_id))).scalars().all())

        result = await session.execute(select(Product.product_id, Product.product_name, Product.productdetails))
        products = [
            {"product_id": r[0], "product_name": r[1], "productdetails": r[2] or {}}
            for r in result.all() if r[0] not in already_embedded
        ]

        if not products:
            print("⚠️ No product pending an embedding! Run the Product seeder first (or everyone already has an embedding).")
            return

        print(f"📣 Generating embeddings for {len(products)} real products | chaos={chaos_rate:.2%}")
        embeddings = get_product_embedding_seeders(products, chaos_rate=chaos_rate, apply_chaos=apply_chaos)

        try:
            total = await insert_in_batches(session, ProductEmbeddingModel, embeddings, batch_size=200)
            print(f"✅ {total} embeddings seeded successfully!")
        except Exception as e:
            await session.rollback()
            print(f"❌ Error seeding embeddings: {e}")


if __name__ == "__main__":
    parser = build_parser("Seeder for product.productembedding (fan-out of real products)")
    add_chaos_args(parser, default_chaos_rate=0.05)
    args = parser.parse_args()
    chaos_rate, apply_chaos = resolve_chaos_args(args, default_chaos_rate=0.05)

    asyncio.run(seed_product_embeddings(chaos_rate=chaos_rate, apply_chaos=apply_chaos))
